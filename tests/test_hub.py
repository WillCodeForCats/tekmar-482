def report(method, **fields):
    """Build a packet as the gateway would send it."""
    return TrpcPacket(service="Report", method=method, **fields)


def method_of(packet):
    """Return the method name of a packet."""
    return name_from_methodID[packet.header["methodID"]]


class FakeSocket:
    """Socket that returns scripted reads and records writes.

    When the scripted reads run out, the hub's run loop is stopped.
    """

    def __init__(self, hub, reads=(), is_open=True, open_results=()):
        """Initialize the fake socket.

        open_results scripts what each open() call returns; once used up,
        open() succeeds.
        """
        self.hub = hub
        self.reads = list(reads)
        self.is_open = is_open
        self.open_results = list(open_results)
        self.opened = 0
        self.written = []
        self.closed = 0
        self.error = "connection refused"

    async def open(self):
        """Pretend to connect."""
        self.opened += 1
        self.is_open = self.open_results.pop(0) if self.open_results else True
        return self.is_open

    async def close(self):
        """Pretend to close."""
        self.closed += 1
        self.is_open = False

    async def write(self, packet):
        """Record a written packet."""
        self.written.append(packet)

    async def read(self):
        """Return the next scripted read, raising it if it is an exception."""
        if not self.reads:
            self.hub._inRun = False
            return None
        item = self.reads.pop(0)
        if isinstance(item, BaseException):
            raise item
        return item


