class FakeGateway(FakeSocket):
    """Socket that answers setup requests like a gateway with two devices.

    Address 1001 is a thermostat and address 1002 is an unknown device type.
    """

    TYPES = {1001: THERMOSTAT_TYPE, 1002: UNKNOWN_TYPE}

    async def write(self, packet):
        """Record the packet and queue the gateway's answer."""
        await super().write(packet)
        method = method_of(packet)
        address = packet.body["address"]

        if method == "FirmwareRevision":
            self.reads.append(report(method, revision=0x0102))
        elif method == "ProtocolVersion":
            self.reads.append(report(method, version=3))
        elif method == "SetbackEnable":
            self.reads.append(report(method, enable=packet.body["enable"]))
        elif method == "DeviceInventory":
            self.reads.extend(report(method, address=a) for a in (1001, 1002, 0))
        elif method == "DeviceType":
            self.reads.append(report(method, address=address, type=self.TYPES[address]))
        elif method == "DeviceVersion":
            self.reads.append(report(method, address=address, j_number=1234))
        elif method == "DeviceAttributes":
            self.reads.append(report(method, address=address, attributes=0b1001))
        elif method == "SetbackEvents":
            self.reads.append(report(method, address=address, events=3))
        elif method == "ReportingState" and packet.body["state"] == 1:
            self.reads.append(report(method, state=1))

    async def read(self):
        """Return the next answer, or None when there is nothing to read."""
        return self.reads.pop(0) if self.reads else None


