async def test_failed_background_task_is_logged(hass, hub, caplog):
    """Test a tracked task that crashes logs its exception."""

    async def crash():
        raise RuntimeError("bug")

    hub.add_task(hass.async_create_background_task(crash(), "tekmar_crash"))
    await hass.async_block_till_done()

    assert "Background task tekmar_crash failed" in caplog.text
    assert "RuntimeError: bug" in caplog.text


async def test_cancelled_background_task_is_not_logged(hass, hub, caplog):
    """Test tasks cancelled by shutdown do not log an error."""
    hub._sock = FakeSocket(hub)

    async def wait_forever():
        await asyncio.Event().wait()

    task = hass.async_create_background_task(wait_forever(), "tekmar_wait")
    hub.add_task(task)

    await hub.shutdown()
    await hass.async_block_till_done()

    assert task.cancelled()
    assert "Background task" not in caplog.text


