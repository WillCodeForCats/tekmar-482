def test_str_is_uppercase_hex_with_newline():
    """Test a packet is written as uppercase hex bytes ending in a newline."""
    assert str(Packet(TYPE_TRPC, [0xAB, 0x01])) == "06AB01\n"


def test_joined_puts_type_before_data():
    """Test the packet type is the first byte of the joined sequence."""
    assert Packet(TYPE_TRPC, [1, 2]).joined() == [TYPE_TRPC, 1, 2]


def test_default_packet_is_empty_general_packet():
    """Test a packet with no arguments is a general packet with no data."""
    packet = Packet()

    assert packet.type == TYPE_GENERAL
    assert packet.data == []


def test_from_str_round_trips():
    """Test a packet converted to a string converts back to the same packet."""
    packet = Packet.from_str(str(Packet(TYPE_TRPC, [0x00, 0xFF, 0x7A])).rstrip())

    assert packet.type == TYPE_TRPC
    assert packet.data == [0x00, 0xFF, 0x7A]


def test_from_str_accepts_lowercase_and_bytes():
    """Test lowercase hex and bytes input from the socket are both parsed."""
    assert Packet.from_str("06ab").joined() == [6, 0xAB]
    assert Packet.from_str(b"06AB").joined() == [6, 0xAB]


def test_from_str_ignores_trailing_odd_character():
    """Test a dangling half byte at the end of the string is dropped."""
    assert Packet.from_str("01AB0").joined() == [1, 0xAB]


@pytest.mark.parametrize("text", ["", "0", "ZZ", "01G2"])
def test_from_str_returns_empty_packet_for_bad_input(text):
    """Test empty, too short, or invalid hex input gives an empty packet."""
    packet = Packet.from_str(text)

    assert packet.type == TYPE_GENERAL
