from custom_components.tekmar_482.trpc.fields import FieldList, Int8, Int16, Record

FORMAT = FieldList("Example", Int16("address"), Int8("setback"), Int8("setpoint"))


def test_create_unpacks_little_endian_values():
    """Test data bytes are unpacked into named values."""
    record, extra = Record.create(FORMAT, [0xE9, 0x03, 0x01, 0x8C])

    assert record.values == {"address": 1001, "setback": 1, "setpoint": 140}
    assert extra == []


def test_create_keeps_extra_data():
    """Test bytes beyond the record format are returned as extra data."""
    record, extra = Record.create(FORMAT, [0xE9, 0x03, 0x01, 0x8C, 0x55])

    assert record["setpoint"] == 140
    assert extra == [0x55]


def test_create_pads_missing_data_with_zeros():
    """Test short data is padded with zeros and no data gives all zeros."""
    short, _ = Record.create(FORMAT, [0xE9])
    empty, _ = Record.create(FORMAT)

    assert short.values == {"address": 0xE9, "setback": 0, "setpoint": 0}
    assert empty.values == {"address": 0, "setback": 0, "setpoint": 0}


def test_pack_round_trips_and_applies_keyword_values():
    """Test packing returns the original bytes, updated by keyword values."""
    record, _ = Record.create(FORMAT, [0xE9, 0x03, 0x01, 0x8C])

    assert record.pack()[0] == [0xE9, 0x03, 0x01, 0x8C]
    assert record.pack(setpoint=0x50)[0] == [0xE9, 0x03, 0x01, 0x50]
    assert record["setpoint"] == 0x50


def test_set_ignores_unknown_fields():
    """Test set() only changes fields that are in the record format."""
    record, _ = Record.create(FORMAT)

    record.set(setback=2, unknown=5)

    assert record.values == {"address": 0, "setback": 2, "setpoint": 0}


def test_get_defaults_unknown_fields_to_zero():
    """Test get() returns 0 for names that are not in the record."""
    record, _ = Record.create(FORMAT, [0xE9, 0x03, 0x01, 0x8C])

    assert record.get("address", "unknown") == {"address": 1001, "unknown": 0}


def test_item_access():
    """Test dictionary-style access, including the 0 default for unknown keys."""
    record, _ = Record.create(FORMAT)

    record["setback"] = 3

