# Issue #112: options flow ----------------------------------------------------


@pytest.mark.parametrize(
    ("options", "default"),
    [({}, False), ({CONF_SETBACK_ENABLE: True}, True)],
)
async def test_options_flow_shows_current_setting(hass, options, default):
    """Test the options flow opens with the stored setback setting.

    Issue #112: opening the options flow failed with AttributeError because
    the handler set self.config_entry, which HA made read-only.
    """
    entry = make_entry(hass, options=options)

    result = await hass.config_entries.options.async_init(entry.entry_id)

    assert result["type"] is FlowResultType.FORM
    assert result["step_id"] == "init"
    schema_defaults = {str(key): key.default() for key in result["data_schema"].schema}
    assert schema_defaults == {CONF_SETBACK_ENABLE: default}


async def test_options_flow_saves_setting(hass):
    """Test submitting the options flow stores the setback setting (issue #112)."""
    entry = make_entry(hass)
    result = await hass.config_entries.options.async_init(entry.entry_id)

    result = await hass.config_entries.options.async_configure(
        result["flow_id"], {CONF_SETBACK_ENABLE: True}
    )

    assert result["type"] is FlowResultType.CREATE_ENTRY
    assert entry.options == {CONF_SETBACK_ENABLE: True}


