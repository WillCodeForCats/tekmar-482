# Issue #77: aux heat moved from the climate entity to a switch --------------


async def test_emergency_heat_is_a_switch(hass, entry, hub):
    """Test emergency heat is a switch, not a climate aux heat feature.

    Issue #77: HA deprecated climate aux heat, so it was moved to a switch.
    """
    await add_thermostat(hub, device_type=THERMOSTAT_557)

    climates = await setup_platform(hass, entry, climate)
    switches = await setup_platform(hass, entry, switch)

    (thermostat,) = climates
    assert not hasattr(thermostat, "is_aux_heat")
    assert not hasattr(thermostat, "async_turn_aux_heat_on")
    assert len(of_type(switches, switch.EmergencyHeat)) == 1


async def test_thermostat_without_emergency_heat_has_no_switch(hass, entry, hub):
    """Test only thermostats with emergency heat get the switch (issue #77)."""
    await add_thermostat(hub, device_type=THERMOSTAT_527)

    switches = await setup_platform(hass, entry, switch)

    assert of_type(switches, switch.EmergencyHeat) == []


async def test_emergency_heat_switch_sets_and_restores_mode(hass, entry, hub):
    """Test the switch sets emergency mode and restores the prior mode (issue #77)."""
    device = await add_thermostat(hub, device_type=THERMOSTAT_557)
    (emergency,) = of_type(
        await setup_platform(hass, entry, switch), switch.EmergencyHeat
    )
    await device.set_mode_setting(0x03)  # auto
    hub._tx_queue.clear()

    await emergency.async_turn_on()
    await device.set_mode_setting(0x06)
    assert emergency.is_on is True

    await emergency.async_turn_off()

    sent = [
        (name_from_methodID[p.header["methodID"]], p.body["mode"])
        for p in hub._tx_queue
    ]
    assert sent == [("ModeSetting", 0x06), ("ModeSetting", 0x03)]


