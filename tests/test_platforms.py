def inventory(device_type, address, attributes=0):
    """Return a device inventory record, as hub setup builds it."""
    attrs = DeviceAttributes()
    attrs.attrs = attributes
    return {
        "type": device_type,
        "entity": f"Tekmarnet Device {address}",
        "version": 120800,  # the gateway reports an int
        "attributes": attrs,
        "events": 0,
    }


async def add_thermostat(hub, device_type=THERMOSTAT_527, address=1001, **kwargs):
    """Add an initialized thermostat to the hub and return it."""
    device = TekmarThermostat(address, inventory(device_type, address, **kwargs), hub)
    await device.init_device()
    hub.tha_devices.append(device)
    return device


def add_setpoint(hub, device_type=SETPOINT_161, address=2001):
    """Add an initialized setpoint control to the hub and return it."""
    device = TekmarSetpoint(address, inventory(device_type, address), hub)
    device.init_device()
    hub.tha_devices.append(device)
    return device


async def setup_platform(hass, entry, platform):
    """Run a platform's setup and return the entities it adds."""
    added = []
    await platform.async_setup_entry(hass, entry, added.extend)
    return added


def of_type(entities, cls):
    """Return the entities that are instances of cls."""
    return [e for e in entities if isinstance(e, cls)]


