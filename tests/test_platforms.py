# Issue #102: SlabSetpoint attribute name -------------------------------------


@pytest.mark.parametrize(("attributes", "enabled"), [(SLAB_SETPOINT_ATTR, 1), (0, 0)])
async def test_floor_entities_enabled_by_slab_attribute(
    hass, entry, hub, attributes, enabled
):
    """Test floor entities are enabled only if the device has a slab sensor.

    Issue #102: these entities read attributes.Slab_Setpoint, which does not
    exist, and setup failed with AttributeError.
    """
    await add_thermostat(hub, attributes=attributes)

