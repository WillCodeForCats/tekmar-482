async def test_saved_settings_are_kept_together(hass, hass_storage):
    """Test saving a setting keeps the entry's other saved settings."""
    storage = StoredData(hass, "entry_1")

    await storage.put_setting("1001_config_vent_mode", True)
    await storage.put_setting("storage", True)

    reloaded = StoredData(hass, "entry_1")
    assert await reloaded.get_setting("1001_config_vent_mode") is True
    assert await reloaded.get_setting("storage") is True


async def test_saved_setting_survives_restart(hass, hass_storage):
    """Test a device setting is still there after the hub starts again.

    On every start, the hub saves the "storage" marker before the devices
    read their settings.
    """
    await StoredData(hass, "entry_1").put_setting("1001_config_vent_mode", True)

    restarted = StoredData(hass, "entry_1")
    await restarted.put_setting("storage", True)

    assert await restarted.get_setting("1001_config_vent_mode") is True


async def test_settings_are_kept_per_entry(hass, hass_storage):
    """Test saving a setting for one entry leaves other entries alone."""
    await StoredData(hass, "entry_1").put_setting("storage", True)
    await StoredData(hass, "entry_2").put_setting("storage", False)

    assert await StoredData(hass, "entry_1").get_setting("storage") is True
    assert await StoredData(hass, "entry_2").get_setting("storage") is False


