# Concurrent saves ------------------------------------------------------------


@pytest.fixture
def file_like_store():
    """Make every Store load and save behave like the real settings file.

    The test storage mock shares one dict between Store objects. A real
    load awaits a file read and returns a new object, so separate Store
    objects can each load the file before the other saves.
    """
    disk = {}

    async def load(self):
        await asyncio.sleep(0)
        return copy.deepcopy(disk.get(self.key))

    async def save(self, data):
        await asyncio.sleep(0)
        disk[self.key] = copy.deepcopy(data)

    with (
        patch.object(Store, "async_load", load),
        patch.object(Store, "async_save", save),
    ):
        yield disk


async def test_entries_saving_at_once_keep_both(hass, file_like_store):
    """Test two entries saving at the same time do not overwrite each other."""
    await asyncio.gather(
        StoredData(hass, "entry_1").put_setting("storage", True),
        StoredData(hass, "entry_2").put_setting("storage", True),
    )

    assert set(file_like_store[STORAGE_KEY]) == {"entry_1", "entry_2"}


async def test_settings_saved_at_once_are_all_kept(hass, file_like_store):
    """Test two settings saved at the same time for one entry are both kept."""
    storage = StoredData(hass, "entry_1")

    await asyncio.gather(
        storage.put_setting("1001_config_vent_mode", True),
        storage.put_setting("1002_config_vent_mode", False),
    )

    assert file_like_store[STORAGE_KEY] == {
        "entry_1": {"1001_config_vent_mode": True, "1002_config_vent_mode": False}
    }


async def test_remove_entry_while_another_entry_saves(hass, file_like_store):
    """Test removing an entry does not undo another entry's save."""
    entry = _entry()
    await StoredData(hass, entry.entry_id).put_setting("storage", True)

    await asyncio.gather(
        async_remove_entry(hass, entry),
        StoredData(hass, "other_entry").put_setting("storage", True),
    )

    assert set(file_like_store[STORAGE_KEY]) == {"other_entry"}
