@pytest.fixture
def loop_file_opens(hass, disk_store):
    """Record files under the config directory opened on the event loop.

    HA's blocking call detection skips open() in tests, so this does the
    same check: an open() with a running loop in its thread blocks the loop.
    Store reads and writes run in executor threads, which have no loop.
    """
    config_dir = hass.config.config_dir
    real_open = builtins.open
    opened = []

    def checked_open(file, *args, **kwargs):
        try:
            asyncio.get_running_loop()
        except RuntimeError:
            pass
        else:
            if str(file).startswith(config_dir):
                opened.append(str(file))
        return real_open(file, *args, **kwargs)

    with patch("builtins.open", checked_open):
        yield opened


async def test_settings_file_is_not_opened_in_event_loop(hass, loop_file_opens):
    """Test saving and loading settings does not open files on the loop.

    Issue #83: the settings pickle file was opened inside the event loop,
    and HA logged "Detected blocking call to open inside the event loop".
    """
    await StoredData(hass, "entry_1").put_setting("1001_config_vent_mode", True)
    restarted = StoredData(hass, "entry_1")
    assert await restarted.get_setting("1001_config_vent_mode") is True

    assert loop_file_opens == []

    # The setting was really written to the file, not just held in memory.
    settings_file = Path(hass.config.path(".storage", STORAGE_KEY))
    saved = json.loads(settings_file.read_text(encoding="utf-8"))
    assert saved["data"] == {"entry_1": {"1001_config_vent_mode": True}}
