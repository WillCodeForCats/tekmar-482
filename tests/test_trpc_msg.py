from custom_components.tekmar_482.packet import TYPE_GENERAL, TYPE_TRPC, Packet
from custom_components.tekmar_482.trpc_msg import (
    TrpcPacket,
    method_formats,
    methodID_from_name,
    name_from_methodID,
    name_from_serviceID,
    service_formats,
    serviceID_from_name,
)


def test_service_lookups_are_inverse():
    """Test every service ID maps to its name and back."""
    assert name_from_serviceID == {
        sid: fmt.name for sid, fmt in service_formats.items()
    }
    for sid, name in name_from_serviceID.items():
        assert serviceID_from_name[name] == sid


def test_method_lookups_are_inverse():
    """Test every method ID maps to its name and back."""
    assert name_from_methodID == {mid: fmt.name for mid, fmt in method_formats.items()}
    assert len(methodID_from_name) == len(name_from_methodID)
    for mid, name in name_from_methodID.items():
        assert methodID_from_name[name] == mid


def test_packet_from_names_sets_header_and_body():
    """Test service and method names select the IDs and body format."""
    packet = TrpcPacket(
        service="Report", method="HeatSetpoint", address=1001, setback=1, setpoint=140
    )

    assert packet.header.values == {
        "serviceID": serviceID_from_name["Report"],
        "methodID": methodID_from_name["HeatSetpoint"],
    }
    assert packet.body.values == {"address": 1001, "setback": 1, "setpoint": 140}


def test_unknown_method_gets_empty_body():
    """Test an unknown method name gives a packet with an empty body."""
    packet = TrpcPacket(service="Report", method="NotAMethod")

    assert packet.header["methodID"] == 0
    assert packet.body.values == {}


def test_packet_round_trips_through_wire_format():
    """Test a packet written to the wire reads back with the same values."""
    sent = TrpcPacket(service="Report", method="CurrentTemperature", address=1002)
    sent.body["temp"] = 0x1234

    wire = str(sent.to_tpck())
    received = TrpcPacket.from_rx_packet(wire.rstrip("\n"))

    assert wire.startswith(f"{TYPE_TRPC:02X}")
    assert received.header.values == sent.header.values
    assert received.body.values == {"address": 1002, "temp": 0x1234}
    assert received.extra == []


def test_from_rx_packet_ignores_non_trpc_packets():
    """Test packets of another type are not decoded as tRPC messages."""
    wire = str(Packet(TYPE_GENERAL, [0x02, 0x0F, 0x01])).rstrip("\n")

    assert TrpcPacket.from_rx_packet(wire) is None


def test_from_rx_packet_with_unknown_method_keeps_data_as_extra():
    """Test the body of an unknown method is kept as extra data."""
    wire = str(Packet(TYPE_TRPC, [0x02, 0xEF, 0xBE, 0x00, 0x00, 0xAA])).rstrip("\n")

    received = TrpcPacket.from_rx_packet(wire)

    assert received.header["methodID"] == 0xBEEF
    assert received.body.values == {}
    assert received.extra == [0xAA]


